"""Puts the app name from tools/brand/brand.json everywhere the user can see it.

    python3 tools/brand/apply_name.py          # rewrite strings and BrandName.kt
    python3 tools/brand/apply_name.py check    # CI: fail if anything still shows another name

brand.json is the one place the name lives. This script writes it into:
  * every core string resource (all languages): the upstream name and the previous name are replaced;
  * core/src/main/java/tv/own/owntv/core/brand/BrandName.kt, the constant code reads.
Change the name: edit brand.json ("name"), run this script, commit the result.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
BRAND = ROOT / 'tools' / 'brand' / 'brand.json'
RES = ROOT / 'core' / 'src' / 'main' / 'res'
KT = ROOT / 'core' / 'src' / 'main' / 'java' / 'tv' / 'own' / 'owntv' / 'core' / 'brand' / 'BrandName.kt'
STATE = ROOT / 'tools' / 'brand' / '.applied_name'   # the name the strings currently carry


def kotlin(b):
    return (
        '// Generated by tools/brand/apply_name.py from tools/brand/brand.json. Do not edit by hand.\n'
        'package tv.own.owntv.core.brand\n\n'
        '/** The app\'s name as code needs it (User-Agent, report headers, folder names). */\n'
        'object BrandName {\n'
        f'    const val NAME: String = "{b["name"]}"\n'
        f'    const val SHORT: String = "{b["short_name"]}"\n'
        '}\n'
    )


def main():
    b = json.loads(BRAND.read_text(encoding='utf-8'))
    name = b['name']
    olds = {b['upstream_name']}
    if STATE.is_file():
        olds.add(STATE.read_text(encoding='utf-8').strip())
    olds.discard(name)
    # whole-word only: OwnTVPerf-like identifiers never reach string resources, but be strict anyway
    pat = re.compile('|'.join(r'(?<![A-Za-z0-9_])' + re.escape(o) for o in sorted(olds, key=len, reverse=True))) if olds else None
    check = len(sys.argv) > 1 and sys.argv[1] == 'check'
    stale = []
    for f in sorted(RES.glob('values*/*.xml')):
        if not (f.name.startswith('strings') or f.name == 'donottranslate.xml'):
            continue
        s = f.read_text(encoding='utf-8')
        n = pat.sub(name, s) if pat else s
        if n != s:
            stale.append(f.relative_to(ROOT))
            if not check:
                f.write_text(n, encoding='utf-8')
    # The wordmark in capitals, its two halves drawn in two colours: generated, like app_name.
    dnt = RES / 'values' / 'donottranslate.xml'
    d = dnt.read_text(encoding='utf-8')
    first, second = (w.upper() for w in b['wordmark'])
    lines = (f'    <string name="brand_wordmark_first" translatable="false">{first}</string>\n'
             f'    <string name="brand_wordmark_second" translatable="false">{second}</string>\n')
    d2 = re.sub(r'    <string name="brand_wordmark_(first|second)"[^\n]*\n', '', d)
    d2 = d2.replace('    <string name="app_name"', lines + '    <string name="app_name"', 1)
    if d2 != d:
        stale.append(dnt.relative_to(ROOT))
        if not check:
            dnt.write_text(d2, encoding='utf-8')
    k = kotlin(b)
    if not KT.is_file() or KT.read_text(encoding='utf-8') != k:
        stale.append(KT.relative_to(ROOT))
        if not check:
            KT.write_text(k, encoding='utf-8')
    if check:
        if stale:
            print('The app name is not applied everywhere; run python3 tools/brand/apply_name.py:')
            for p in stale:
                print('  ', p)
            return 1
        print(f'App name "{name}" applied everywhere')
        return 0
    STATE.write_text(name + '\n', encoding='utf-8')
    print(f'"{name}" written into {len(stale)} file(s)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
