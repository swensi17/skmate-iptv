# ---- geometry (108-unit canvas) ---------------------------------------------------------------------
TILE = (31, 31, 77, 77, 13)                    # x0, y0, x1, y1, corner radius
EDGE_Y = 70                                    # the tile's lower band starts here
PLAY = [(47.5, 40.5), (47.5, 61.5), (65.5, 51)]
PLAY_SW = 4                                    # rounded corners: the triangle is stroked with a round join
BAR = (41, 66.2, 67, 69.6, 1.7)                # live bar track
BAR_FILL = 0.62                                # share of the track that is filled
