def rgb(h, a=255):
    h = h.lstrip('#')
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)


# ---- bitmaps ----------------------------------------------------------------------------------------

class Canvas:
    def __init__(self, px, vb):
        self.w = px * SS
        self.o, self.size = vb
        self.k = self.w / self.size

    def p(self, x, y): return ((x - self.o) * self.k, (y - self.o) * self.k)
    def box(self, x0, y0, x1, y1): return (*self.p(x0, y0), *self.p(x1, y1))
    def layer(self): return Image.new('RGBA', (self.w, self.w), (0, 0, 0, 0))
    def mask(self): return Image.new('L', (self.w, self.w), 0)

    def rrect(self, m, r, fill=255):
        x0, y0, x1, y1, rad = r
        ImageDraw.Draw(m).rounded_rectangle(self.box(x0, y0, x1, y1), radius=rad * self.k, fill=fill)

    def play(self, m, sw):
        d = ImageDraw.Draw(m)
        pts = [self.p(a, b) for a, b in PLAY]
        d.polygon(pts, fill=255)
        r = sw / 2 * self.k
        for i in range(3):
            d.line([pts[i], pts[(i + 1) % 3]], fill=255, width=int(round(sw * self.k)))
        for x, y in pts:
            d.ellipse((x - r, y - r, x + r, y + r), fill=255)


def mark(p, px, vb=VB_FULL, shadow=True):
    c = Canvas(px, vb)
    obj = c.layer()
    tile = c.mask()
    c.rrect(tile, TILE)
    obj.paste(rgb(p['tile']), (0, 0), tile)
    band = tile.copy()
    ImageDraw.Draw(band).rectangle((0, 0, c.w, int(c.p(0, EDGE_Y)[1])), fill=0)
    obj.paste(rgb(p['edge']), (0, 0), band)
    pm = c.mask()
    c.play(pm, PLAY_SW)
    obj.paste(rgb(p['play']), (0, 0), pm)
    x0, y0, x1, y1, r = BAR
    bm = c.mask()
    c.rrect(bm, BAR)
    obj.paste(rgb(p['bar']), (0, 0), bm)
    fm = c.mask()
    c.rrect(fm, (x0, y0, x0 + (x1 - x0) * BAR_FILL, y1, r))
    obj.paste(rgb(p['acc']), (0, 0), fm)
    out = obj
    if shadow:
        a = obj.getchannel('A').filter(ImageFilter.GaussianBlur(SHADOW['blur'] * c.k))
        a = a.point(lambda v: int(v * SHADOW['alpha']))
        sh = c.layer()
        sh.paste((0, 0, 0, 255), (0, int(round(SHADOW['dy'] * c.k))), a)
        out = Image.alpha_composite(sh, obj)
    return out.resize((px, px), Image.LANCZOS)


def pil_font(path, size):
    return ImageFont.truetype(path, size)


def text_size(f, text):
    b = f.getbbox(text, anchor='ls')
    return f.getlength(text), b


def draw_word(img, x, base, f, accent, white='#FFFFFF'):
    d = ImageDraw.Draw(img)
    d.text((x, base), WORD_A, font=f, fill=white, anchor='ls')
    d.text((x + f.getlength(WORD_A), base), WORD_B, font=f, fill=accent, anchor='ls')
    return x + f.getlength(WORD_A + WORD_B)


def lockup(p, mark_px, font_px, font_path, white='#FFFFFF', accent=None, pad=10):
    f = pil_font(font_path, font_px)
    word = WORD_A + WORD_B
    ww, b = text_size(f, word)
    gap = round(mark_px * .24)
    w = pad * 2 + mark_px + gap + int(ww) + 4
    h = pad * 2 + max(mark_px, int(font_px * 1.25))
    img = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    img.alpha_composite(mark(p, mark_px, VB_TIGHT, shadow=False), (pad, (h - mark_px) // 2))
    draw_word(img, pad + mark_px + gap, h / 2 - (b[1] + b[3]) / 2, f, accent or p['acc'], white)
    return img


def banner(p, w, h, font_path):
    """TV banner (320 x 180 at xhdpi): the tile and the wordmark side by side, centred."""
    s = h / 180
    img = Image.new('RGBA', (w, h), rgb(p['field']))
    mk = round(96 * s)
    f = pil_font(font_path, round(46 * s))
    ww, b = text_size(f, WORD_A + WORD_B)
    gap = round(10 * s)
    x0 = round((w - (mk + gap + ww)) / 2)
    img.alpha_composite(mark(p, mk, VB_TIGHT, shadow=False), (x0, round((h - mk) / 2)))
    draw_word(img, x0 + mk + gap, h / 2 - (b[1] + b[3]) / 2, f, p['acc'])
    return img


def splash_name(p, w, h, font_path):
    """Android 12+ launch-screen branding image (200 x 80 dp): the wordmark, centred."""
    f = pil_font(font_path, round(h * .42))
    ww, b = text_size(f, WORD_A + WORD_B)
    img = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    draw_word(img, (w - ww) / 2, h / 2 - (b[1] + b[3]) / 2, f, p['acc'])
    return img


# ---- vector drawables -------------------------------------------------------------------------------

def fmt(v):
    return ('%.3f' % v).rstrip('0').rstrip('.')


def rr_path(x0, y0, x1, y1, r, ccw=False):
    if ccw:
        return (f'M{fmt(x0 + r)},{fmt(y0)}A{fmt(r)},{fmt(r)} 0 0 0 {fmt(x0)},{fmt(y0 + r)}V{fmt(y1 - r)}'
                f'A{fmt(r)},{fmt(r)} 0 0 0 {fmt(x0 + r)},{fmt(y1)}H{fmt(x1 - r)}A{fmt(r)},{fmt(r)} 0 0 0 {fmt(x1)},{fmt(y1 - r)}'
                f'V{fmt(y0 + r)}A{fmt(r)},{fmt(r)} 0 0 0 {fmt(x1 - r)},{fmt(y0)}Z')
    return (f'M{fmt(x0 + r)},{fmt(y0)}H{fmt(x1 - r)}A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x1)},{fmt(y0 + r)}V{fmt(y1 - r)}'
            f'A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x1 - r)},{fmt(y1)}H{fmt(x0 + r)}A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x0)},{fmt(y1 - r)}'
            f'V{fmt(y0 + r)}A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x0 + r)},{fmt(y0)}Z')


def rounded_triangle(r, n=12):
    """PLAY grown by r with round corners, as a clockwise polygon. PLAY itself runs counter-clockwise
    on screen, so it is walked in reverse: the outward normals and the corner arcs need clockwise."""
    pts = list(reversed(PLAY))
    out = []
    for i in range(3):
        px, py = pts[i]
        ax, ay = pts[i - 1]
        bx, by = pts[(i + 1) % 3]

        def normal(x0, y0, x1, y1):
            dx, dy = x1 - x0, y1 - y0
            ln = math.hypot(dx, dy)
            return (dy / ln, -dx / ln)
        n1, n2 = normal(ax, ay, px, py), normal(px, py, bx, by)
        a1, a2 = math.atan2(n1[1], n1[0]), math.atan2(n2[1], n2[0])
        while a2 < a1:
            a2 += 2 * math.pi
        for k in range(n + 1):
            t = a1 + (a2 - a1) * k / n
            out.append((px + r * math.cos(t), py + r * math.sin(t)))
    return out


def poly_path(poly, reverse=False):
    pts = list(reversed(poly)) if reverse else poly
    return 'M' + 'L'.join(f'{fmt(x)},{fmt(y)}' for x, y in pts) + 'Z'


PLAY_PATH = poly_path(rounded_triangle(PLAY_SW / 2))
TILE_PATH = rr_path(*TILE)
EDGE_CLIP = f'M0,{EDGE_Y}H108V108H0Z'


def bar_fill_rect():
    x0, y0, x1, y1, r = BAR
    return (x0, y0, x0 + (x1 - x0) * BAR_FILL, y1, r)


def _p(d, fill, name=None, ind=8, alpha=None):
    a = [f'android:pathData="{d}"', f'android:fillColor="{fill}"']
    if name:
        a.insert(0, f'android:name="{name}"')
    if alpha is not None:
        a.append(f'android:fillAlpha="{alpha}"')
    return ' ' * ind + '<path ' + ' '.join(a) + '/>\n'


def _vec(body, vb, size_dp):
    o, s = vb
    return (f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{s}" android:viewportHeight="{s}">\n'
            f'    <group android:translateX="{-o}" android:translateY="{-o}">\n{body}    </group>\n</vector>\n')


def flat_body(p, ind=8):
    b = _p(TILE_PATH, p['tile'], ind=ind)
    b += f'{" " * ind}<group>\n{" " * ind}    <clip-path android:pathData="{EDGE_CLIP}"/>\n'
    b += _p(TILE_PATH, p['edge'], ind=ind + 4) + f'{" " * ind}</group>\n'
    b += _p(PLAY_PATH, p['play'], ind=ind)
    b += _p(rr_path(*BAR), p['bar'], ind=ind)
    b += _p(rr_path(*bar_fill_rect()), p['acc'], ind=ind)
    return b


def vector_mark(p, vb=VB_TIGHT, size_dp=56):
    return _vec(flat_body(p), vb, size_dp)


def mono_path():
    # tile clockwise, play and bar counter-clockwise: nonZero fill cuts them out
    return TILE_PATH + poly_path(rounded_triangle(PLAY_SW / 2), reverse=True) + rr_path(*BAR, ccw=True)


def vector_mono(vb=VB_TIGHT, size_dp=24, colour='#FFFFFFFF'):
    return _vec(_p(mono_path(), colour), vb, size_dp)


def vector_splash_anim(p):
    """Launch animation, 700 ms: the tile pops in, the play fades in, the live bar fills."""
    x0 = BAR[0]
    body = (f'        <group android:name="tile" android:pivotX="54" android:pivotY="54" android:scaleX="0.6" android:scaleY="0.6">\n'
            + _p(TILE_PATH, p['tile'], 't', 12, alpha='0')
            + f'            <group>\n                <clip-path android:pathData="{EDGE_CLIP}"/>\n'
            + _p(TILE_PATH, p['edge'], 'e', 16, alpha='0') + '            </group>\n'
            + _p(PLAY_PATH, p['play'], 'pl', 12, alpha='0')
            + _p(rr_path(*BAR), p['bar'], 'b', 12, alpha='0')
            + f'            <group android:name="fill" android:pivotX="{x0}" android:scaleX="0">\n'
            + _p(rr_path(*bar_fill_rect()), p['acc'], None, 16) + '            </group>\n'
            + '        </group>\n')
    drawable = ('<vector android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
                f'{body}    </vector>')

    def anim(prop, frm, to, dur, off=0, interp='@android:interpolator/decelerate_quad'):
        return (f'<objectAnimator android:propertyName="{prop}" android:valueFrom="{frm}" android:valueTo="{to}" '
                f'android:valueType="floatType" android:duration="{dur}" android:startOffset="{off}" android:interpolator="{interp}"/>')

    def target(name, anims):
        return (f'    <target android:name="{name}">\n        <aapt:attr name="android:animation">\n'
                f'            <set>{"".join(anims)}</set>\n        </aapt:attr>\n    </target>\n')
    t = target('tile', [anim('scaleX', .6, 1.04, 240), anim('scaleY', .6, 1.04, 240),
                        anim('scaleX', 1.04, 1, 100, 240), anim('scaleY', 1.04, 1, 100, 240)])
    for n in ('t', 'e', 'b'):
        t += target(n, [anim('fillAlpha', 0, 1, 200)])
    t += target('pl', [anim('fillAlpha', 0, 1, 200, 220)])
    t += target('fill', [anim('scaleX', 0, 1, 280, 380)])
    return ('<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt">\n'
            f'    <aapt:attr name="android:drawable">\n    {drawable}\n    </aapt:attr>\n{t}</animated-vector>\n')


def wordmark_vectors(font_path):
    """The in-app wordmark as two vectors on one 988 x 182 canvas (the app overlays them and tints
    the first white, the second with the accent)."""
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.ttLib import TTFont
    tt = TTFont(font_path)
    gs = tt.getGlyphSet()
    cmap = tt.getBestCmap()
    upm = tt['head'].unitsPerEm
    W, H = 988, 182
    # layout in font units: measure ink box of the whole word
    xs, x = [], 0
    for ch in WORD_A + WORD_B:
        g = cmap[ord(ch)]
        xs.append((ch, g, x))
        x += gs[g].width
    from fontTools.pens.boundsPen import BoundsPen
    bp = BoundsPen(gs)
    for ch, g, gx in xs:
        pen = BoundsPen(gs)
        gs[g].draw(pen)
        if pen.bounds:
            b = pen.bounds
            bp.bounds = (b[0] + gx, b[1], b[2] + gx, b[3]) if bp.bounds is None else (
                min(bp.bounds[0], b[0] + gx), min(bp.bounds[1], b[1]), max(bp.bounds[2], b[2] + gx), max(bp.bounds[3], b[3]))
    bx0, by0, bx1, by1 = bp.bounds
    s = min(W / (bx1 - bx0), H / (by1 - by0)) * 0.98
    ox = (W - (bx1 - bx0) * s) / 2 - bx0 * s
    oy = (H + (by1 - by0) * s) / 2 + by0 * s     # flip y: font y-up -> vector y-down
    parts = {'a': '', 'b': ''}
    for i, (ch, g, gx) in enumerate(xs):
        pen = SVGPathPen(gs)
        gs[g].draw(TransformPen(pen, (s, 0, 0, -s, ox + gx * s, oy)))
        parts['a' if i < len(WORD_A) else 'b'] += pen.getCommands()
    out = {}
    for key, name in (('a', 'owntv_wordmark_own'), ('b', 'owntv_wordmark_tv')):
        out[name] = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                     f'    android:width="{W}dp" android:height="{H}dp" android:viewportWidth="{W}" android:viewportHeight="{H}">\n'
                     f'    <path android:pathData="{parts[key]}" android:fillColor="#FFFFFFFF"/>\n</vector>\n')
    return out


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(HEADER + text)


def icon_bg(p):
    return p['field'] if p['tile'].upper().startswith('#F') else p['edge']


def android(res, font_path):
    for key, p in PAL.items():
        for dens, k in DENSITIES.items():
            d = os.path.join(res, f'mipmap-{dens}')
            os.makedirs(d, exist_ok=True)
            mark(p, round(108 * k)).save(os.path.join(d, f'owntv_icon_{key}_foreground.png'))
            d = os.path.join(res, f'drawable-{dens}')
            os.makedirs(d, exist_ok=True)
            splash_name(p, round(200 * k), round(80 * k), font_path).save(os.path.join(d, f'owntv_splash_name_{key}.png'))
        write(os.path.join(res, 'mipmap-anydpi-v26', f'owntv_icon_{key}.xml'),
              '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
              f'    <background android:drawable="@color/owntv_icon_bg_{key}"/>\n'
              f'    <foreground android:drawable="@mipmap/owntv_icon_{key}_foreground"/>\n'
              '    <monochrome android:drawable="@drawable/owntv_icon_monochrome"/>\n</adaptive-icon>\n')
        write(os.path.join(res, 'drawable', f'owntv_mark_{key}.xml'), vector_mark(p))
        write(os.path.join(res, 'drawable', f'owntv_mark_small_{key}.xml'), vector_mark(p, size_dp=32))
        write(os.path.join(res, 'drawable', f'owntv_splash_static_{key}.xml'), vector_mark(p, VB_FULL, 108))
        write(os.path.join(res, 'drawable', f'owntv_splash_{key}.xml'), vector_splash_anim(p))
        d = os.path.join(res, 'drawable-xhdpi')
        os.makedirs(d, exist_ok=True)
        banner(p, 320, 180, font_path).convert('RGB').save(os.path.join(d, f'owntv_banner_{key}.png'))
    logo_android(res)
    colours = {k: icon_bg(p) for k, p in PAL.items()}
    colours[LOGO_KEY] = LOGO_FIELD
    stage = colours.pop('pixel')
    write(os.path.join(res, 'values', 'owntv_icon_colors.xml'),
          '<resources>\n' + ''.join(f'    <color name="owntv_icon_bg_{k}">{v}</color>\n' for k, v in colours.items()) + '</resources>\n')
    write(os.path.join(res, 'values', 'owntv_icon_colors_stage.xml'),
          f'<resources>\n    <color name="owntv_icon_bg_pixel">{stage}</color>\n</resources>\n')
    write(os.path.join(res, 'drawable', 'owntv_icon_monochrome.xml'), vector_mono(VB_FULL, 108))
    write(os.path.join(res, 'drawable', 'owntv_notification.xml'), vector_mono())
    for name, text in wordmark_vectors(font_path).items():
        write(os.path.join(res, 'drawable', f'{name}.xml'), text)
    # A white triangle the app draws over a mark and tints with the accent.
    for name, size in (('owntv_mark_play', 56), ('owntv_mark_play_small', 32)):
        write(os.path.join(res, 'drawable', f'{name}.xml'), _vec(_p(PLAY_PATH, '#FFFFFFFF'), VB_TIGHT, size))


# ---- the logo: the "skmate" wordmark drawn by the customer (skmate_logo.png, transparent, trimmed) ------
LOGO = os.path.join(HERE, 'skmate_logo.png')
LOGO_KEY = 'eggshell'          # the default launcher look: the logo on white
LOGO_FIELD = '#FFFFFF'
LOGO_SK_RIGHT = 244            # x where the "k" ends in skmate_logo.png: the "sk" cut used in the app


def logo_on(w, h, share):
    """The logo centred on a transparent [w] x [h] canvas, [share] of the width wide."""
    logo = Image.open(LOGO).convert('RGBA')
    lw = round(w * share)
    lh = round(logo.height * lw / logo.width)
    out = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    out.alpha_composite(logo.resize((lw, lh), Image.LANCZOS), ((w - lw) // 2, (h - lh) // 2))
    return out


def logo_android(res):
    """The default launcher icon and TV banner: the logo in the middle of a white field; and the "sk"
    cut the app shows at the top of its menu."""
    for dens, k in DENSITIES.items():
        px = round(108 * k)
        # 0.56 of the canvas keeps the wordmark inside the adaptive icon's 66-unit safe circle.
        logo_on(px, px, 0.56).save(os.path.join(res, f'mipmap-{dens}', f'owntv_icon_{LOGO_KEY}_foreground.png'))
    banner = Image.new('RGBA', (320, 180), rgb(LOGO_FIELD))
    banner.alpha_composite(logo_on(320, 180, 0.72))
    banner.convert('RGB').save(os.path.join(res, 'drawable-xhdpi', f'owntv_banner_{LOGO_KEY}.png'))
    logo = Image.open(LOGO).convert('RGBA')
    d = os.path.join(res, 'drawable-nodpi')
    os.makedirs(d, exist_ok=True)
    sk = logo.crop((0, 0, LOGO_SK_RIGHT, logo.height))
    sk.crop(sk.getbbox()).save(os.path.join(d, 'skmate_logo_sk.png'))
    logo.save(os.path.join(d, 'skmate_logo.png'))


def extras(root, font_path):
    for key, p in PAL.items():
        d = os.path.join(root, 'brand', 'app-logos')
        os.makedirs(d, exist_ok=True)
        lockup(p, 150, 104, font_path).save(os.path.join(d, f'logo_{key}.png'))
        lockup(p, 150, 104, font_path, white='#16181D', accent=p['ui']).save(os.path.join(d, f'logo_{key}_light.png'))
        d = os.path.join(root, 'brand', 'app-icons')
        os.makedirs(d, exist_ok=True)
        mark(p, 1024).save(os.path.join(d, f'icon_{key}.png'))
        d = os.path.join(root, 'brand', 'tv-banners')
        os.makedirs(d, exist_ok=True)
        banner(p, 1920, 1080, font_path).convert('RGB').save(os.path.join(d, f'banner_{key}.png'))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('what', choices=['android', 'extras'])
    ap.add_argument('--font', default=os.path.join(HERE, 'fonts', 'Poppins-Bold.ttf'))
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    (android if a.what == 'android' else extras)(a.out, a.font)


if __name__ == '__main__':
    main()
