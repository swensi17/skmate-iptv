"""Renders the SkMate IPTV brand images: launcher icons, TV banners, launch screens, in-app marks and
the wordmark. This file is the one place the brand is drawn; never edit a generated file by hand.

    python tools/brand/render_skmate.py android --out core/src/main/res
    python tools/brand/render_skmate.py extras  --out <repo>/extras

Needs Pillow and fontTools. The wordmark is set in Poppins Bold (OFL, app/src/main/res/font in the
app repository; pass --font to use another file).

The resource names keep the upstream `owntv_` prefix on purpose: they are internal ids, never shown,
and keeping them lets the app's icon picker and launcher aliases work unchanged. What the user sees
(shape, colours, wordmark) is SkMate's own.

The mark: a rounded tile, a rounded play triangle and a "live" bar under it. Coordinates are in the
108-unit adaptive-icon canvas, like every Android launcher icon.
"""
