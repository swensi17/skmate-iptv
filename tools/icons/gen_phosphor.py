def kmap(name, d):
    lines=",\n".join('    OwnTVIcon.%s to "%s"' % (k, v) for k,v in d.items())
    return "private val %s: Map<OwnTVIcon, String> = mapOf(\n%s,\n)\n" % (name, lines)
