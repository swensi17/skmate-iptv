def paths(weight, name):
    f = os.path.join(src, weight, (name + ("" if weight=="regular" else "-"+weight)) + ".svg")
    if not os.path.exists(f): return None
    t = open(f).read()
    ds = re.findall(r'<path[^>]*\sd="([^"]+)"', t)
    other = re.findall(r'<(circle|rect|line|polyline|polygon|ellipse)\b', t)
    if other: raise SystemExit("non-path element in %s: %s" % (f, other))
    return " ".join(ds)
