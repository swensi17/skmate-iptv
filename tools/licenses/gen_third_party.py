"""Builds THIRD_PARTY_LICENSES.md from the licensee report of the release build.

    ./gradlew :app:licenseeAndroidStandardRelease
    python3 tools/licenses/gen_third_party.py          # write the file
    python3 tools/licenses/gen_third_party.py check    # CI: fail if the file is stale

Never edit THIRD_PARTY_LICENSES.md by hand: change dependencies, then re-run this script.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
REPORT = ROOT / "app/build/reports/licensee/androidStandardRelease/artifacts.json"
OUT = ROOT / "THIRD_PARTY_LICENSES.md"

# Components shipped without an SPDX id in their POM; their licence is recorded here by hand.
KNOWN = {
    "uz.skmate.iptv:core": "GPL-3.0 (SkMate IPTV engine)",
    "uz.skmate.iptv:player-core": "GPL-3.0 (SkMate IPTV engine)",
    "uz.skmate.iptv:libmpv": "GPL-3.0-or-later (binaries: mpv, FFmpeg), MIT (wrapper); source: libmpv/",
    "com.github.albfernandez:juniversalchardet": "MPL-1.1 OR GPL OR LGPL (used under the GPL)",
    "com.pierfrancescosoffritti.androidyoutubeplayer:core": "MIT",
}


def licence(a: dict) -> str:
    key = f"{a['groupId']}:{a['artifactId']}"
    if key in KNOWN:
        return KNOWN[key]
    ids = [s["identifier"] for s in a.get("spdxLicenses", [])]
    if ids:
        return " OR ".join(ids)
    urls = [u.get("url", "") for u in a.get("unknownLicenses", [])]
    return ", ".join(u for u in urls if u) or "see project"


def render() -> str:
    artifacts = json.loads(REPORT.read_text())
    lines = [
        "# Third-party licences",
        "",
        "Generated by `tools/licenses/gen_third_party.py` from the licence gate of the release build.",
        "Do not edit by hand. SkMate IPTV itself is GPL-3.0-or-later; see LICENSE and NOTICE.",
        "",
        "| Component | Version | Licence |",
        "|---|---|---|",
    ]
    for a in sorted(artifacts, key=lambda x: (x["groupId"], x["artifactId"])):
        lines.append(f"| `{a['groupId']}:{a['artifactId']}` | {a['version']} | {licence(a)} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "check":
        if not OUT.is_file() or OUT.read_text() != text:
            print("THIRD_PARTY_LICENSES.md is stale: run python3 tools/licenses/gen_third_party.py")
            return 1
        print("THIRD_PARTY_LICENSES.md is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.name} ({text.count(chr(10)) - 7} components)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
